def test_output_is_ruff_clean(tmp_path: Path, source: str) -> None:
    """A generated file a human reads should not be visibly worse than one they write."""
    import shutil
    import subprocess
    import sys

    # Prefer the ruff in the active environment over whatever is on PATH.
    candidate = Path(sys.executable).parent / "ruff"
    ruff = str(candidate) if candidate.exists() else shutil.which("ruff")
    if ruff is None:
        pytest.skip("ruff is not available")

    script = tmp_path / "generated.py"
    script.write_text(source, encoding="utf-8")
    result = subprocess.run(
        [ruff, "check", "--select", "E9,F", "--no-cache", str(script)],
        capture_output=True,
        text=True,
        timeout=120,
    )

    assert result.returncode == 0, result.stdout


