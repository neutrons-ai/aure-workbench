def test_each_free_parameter_is_created_exactly_once(source: str) -> None:
    """Pass 1's guarantee, and the reason the aliasing trap cannot happen."""
    creations = [
        line
        for line in source.splitlines()
        if line.startswith("P['") and "Parameter(" in line
    ]
    keys = [line.split("'")[1] for line in creations]

    assert len(keys) == len(set(keys))


def test_assignments_read_only_from_the_tables(source: str) -> None:
    """Pass 3 never reads from another Experiment; that is the whole design."""
    tree = ast.parse(source)
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign):
            continue
        target = ast.unparse(node.targets[0])
        if not target.startswith(("SAMPLES[", "EXP[")):
            continue
        if ".probe." not in target and "]." not in target:
            continue
        value = ast.unparse(node.value)
        assert value.startswith(("P[", "E[")), (
            f"assignment reads from something other than the table: {target} = {value}"
        )


