def test_generation_is_deterministic() -> None:
    """Same spec, same output -- otherwise every regeneration is a diff."""
    first = generate(table_from(BASE, {"a": 2, "b": 1}), now=FIXED_TIME)
    second = generate(table_from(BASE, {"a": 2, "b": 1}), now=FIXED_TIME)

    assert first == second


def test_no_absolute_paths(source: str) -> None:
    """An absolute path is what made the hand-written scripts unshareable."""
    offenders = [
        line
        for line in source.splitlines()
        if ('"/' in line or "'/" in line) and "PROJECT_ROOT" not in line
    ]

    assert offenders == []


