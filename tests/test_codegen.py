FIXED_TIME = datetime(2026, 8, 5, 12, 0, 0, tzinfo=UTC)

BASE: dict[str, Any] = {
    "schema": "nrw-model/1",
    "name": "demo",
    "materials": {"Air": {"rho": 0.0}, "Film": {"rho": 4.0}, "Si": {"rho": 2.07}},
    "stack": [
        {"name": "Air", "thickness": 0, "roughness": 5},
        {"name": "Film", "thickness": 100, "roughness": 5},
        {"name": "Si"},
    ],
    "states": [
        {
            "name": "a",
            "segments": [
                {"file": "d/a0.txt", "theta": 0.45},
                {"file": "d/a1.txt", "theta": 1.2},
            ],
        },
        {"name": "b", "segments": [{"file": "d/b0.txt", "theta": 0.45}]},
    ],
    "parameters": [
        {"path": "Film.thickness", "range": [50, 200], "per": "state"},
        {"path": "Film.rho", "range": [2, 6], "per": "model"},
    ],
}


def table_from(payload: dict[str, Any], counts: dict[str, int]):
    """Build a parameter table with fabricated measurements."""
    spec = ModelSpec.model_validate(payload)
    measurements = {
        group: [
            Measurement(group, i, f"d/{group}{i}.txt", 0.45, time=float(i * 100))
            for i in range(n)
        ]
        for group, n in counts.items()
    }
    return build_table(spec, measurements)


@pytest.fixture
def source() -> str:
    """A generated script for the base spec."""
    return generate(table_from(BASE, {"a": 2, "b": 1}), now=FIXED_TIME)


