def test_angular_only_emits_zero_wavelength_spread(source: str) -> None:
    assert "dL = 0 * q" in source
    assert "delta_wl_over_wl" not in source


def test_moderator_mode_emits_the_emission_time_polynomial() -> None:
    """Reproducing the REF_L convention exactly is what passed the gate."""
    payload = {**BASE, "probe": {"resolution": "moderator", "dq_is_fwhm": True}}

    source = generate(table_from(payload, {"a": 2, "b": 1}), now=FIXED_TIME)

    assert "def delta_wl_over_wl(wl):" in source
    assert "dL = delta_wl_over_wl(wl) * q" in source
    # The `* q` looks like a units slip; the comment must explain why it stays.
    assert "REF_L convention" in source


def test_sigma_input_is_converted_to_fwhm() -> None:
    payload = {**BASE, "probe": {"resolution": "angular_only", "dq_is_fwhm": False}}

    source = generate(table_from(payload, {"a": 2, "b": 1}), now=FIXED_TIME)

    assert "dq = dq * 2.355" in source


def test_pmath_is_imported_only_when_a_form_needs_it() -> None:
    payload = {
        **BASE,
        # Restricted to the two states: the series' value comes from the
        # constraint, and declaring it free there too would (rightly) be
        # rejected as a double assignment.
        "parameters": [
            {
                "path": "Film.thickness",
                "range": [50, 200],
                "per": "state",
                "in": ["a", "b"],
            },
        ],
        "series": [{"name": "t", "reduced_dir": "d"}],
        "constraints": [
            {
                "series": "t",
                "form": "logistic",
                "from": "a",
                "to": "b",
                "paths": ["Film.thickness"],
            }
        ],
    }

    with_logistic = generate(
        table_from(payload, {"a": 2, "b": 1, "t": 4}), now=FIXED_TIME
    )
    without = generate(table_from(BASE, {"a": 2, "b": 1}), now=FIXED_TIME)

    assert "from bumps.parameter import pmath" in with_logistic
    assert "pmath" not in without


def test_roughness_is_emitted_as_refl1d_interface(source: str) -> None:
    """The spec's friendly name has to become refl1d's actual attribute."""
    payload = {
        **BASE,
        "parameters": [
            {"path": "Film.roughness", "range": [1, 20], "per": "state"},
        ],
    }

    generated = generate(table_from(payload, {"a": 2, "b": 1}), now=FIXED_TIME)

    assert ".interface = P[" in generated
    assert ".roughness = P[" not in generated


def test_post_build_is_emitted_verbatim_and_flagged() -> None:
    payload = {**BASE, "post_build": "problem.name = 'overridden'\n"}

    source = generate(table_from(payload, {"a": 2, "b": 1}), now=FIXED_TIME)

    assert "problem.name = 'overridden'" in source
    assert "escape hatch" in source.lower()
